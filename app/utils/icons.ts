export type IconName = keyof typeof ICONS;

function escapeAttribute(value: string | number) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;");
}

/**
 * Returns a decorative Lucide icon as an SVG string. Unknown names return an
 * empty string so a typo never breaks the surrounding markup.
 */
export function iconSvg(name: string, className = "size-5"): string {
  const node = (ICONS as Record<string, IconNode>)[name];
  if (!node) return "";
  const children = node
    .map(([tag, attrs]) => {
      const attributes = Object.entries(attrs)
        .map(([key, value]) => `${key}="${escapeAttribute(value as string)}"`)
        .join(" ");
      return `<${tag} ${attributes}/>`;
    })
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" class="icon ${escapeAttribute(className)}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${children}</svg>`;
}
